#!/usr/bin/env node
// Builds src/sky/data/bright-stars.js from the Yale Bright Star Catalogue (5th revised ed.).
//
//   node scripts/build-star-catalog.mjs [path/to/catalog]
//
// Without a path the catalogue is downloaded from CDS (VizieR V/50). The output packs each
// star into 6 bytes, brightest first, so quality tiers can take a prefix of the list:
//
//   uint16 RA   (0..65535 → 0..360°)
//   int16  Dec  (±32767 → ±90°)
//   uint8  V    ((V + 1.6) × 25)
//   uint8  B−V  ((B−V + 0.4) × 90)

import { readFile, writeFile } from "node:fs/promises";
import { gunzipSync } from "node:zlib";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz";
const OUTPUT = resolve(dirname(fileURLToPath(import.meta.url)), "../src/sky/data/bright-stars.js");

// Rough B−V by spectral class for the few hundred entries without photometry.
const SPECTRAL_BV = {
  O: [-0.33, -0.31],
  B: [-0.3, -0.02],
  A: [0.0, 0.27],
  F: [0.3, 0.55],
  G: [0.58, 0.79],
  K: [0.81, 1.39],
  M: [1.4, 1.7],
  C: [2.0, 2.4],
  S: [1.6, 1.9],
  N: [2.0, 2.4],
};

const estimateBvFromSpectralType = (spectralType) => {
  const match = /([OBAFGKMCSN])(\d(\.\d)?)?/.exec(spectralType);

  if (!match) {
    return 0.6;
  }

  const [low, high] = SPECTRAL_BV[match[1]];
  const subclass = match[2] ? Number(match[2]) / 10 : 0.5;
  return low + (high - low) * subclass;
};

const parseCatalog = (text) =>
  text
    .split("\n")
    .filter((line) => line.length > 110 && line.slice(75, 77).trim() !== "")
    .map((line) => {
      const raHours = Number(line.slice(75, 77));
      const raMinutes = Number(line.slice(77, 79));
      const raSeconds = Number(line.slice(79, 83));
      const decSign = line[83] === "-" ? -1 : 1;
      const decDegrees = Number(line.slice(84, 86));
      const decMinutes = Number(line.slice(86, 88));
      const decSeconds = Number(line.slice(88, 90));
      const bvText = line.slice(109, 114).trim();

      return {
        ra: (raHours + raMinutes / 60 + raSeconds / 3600) * 15,
        dec: decSign * (decDegrees + decMinutes / 60 + decSeconds / 3600),
        vmag: Number(line.slice(102, 107)),
        bv: bvText ? Number(bvText) : estimateBvFromSpectralType(line.slice(127, 147)),
      };
    })
    .filter((star) => Number.isFinite(star.vmag))
    .sort((a, b) => a.vmag - b.vmag);

const clampByte = (value) => Math.max(0, Math.min(255, Math.round(value)));

const encodeStars = (stars) => {
  const bytes = new Uint8Array(stars.length * 6);
  const view = new DataView(bytes.buffer);

  stars.forEach((star, index) => {
    const offset = index * 6;
    view.setUint16(offset, Math.round((star.ra / 360) * 65536) % 65536, true);
    view.setInt16(offset + 2, Math.round((star.dec / 90) * 32767), true);
    view.setUint8(offset + 4, clampByte((star.vmag + 1.6) * 25));
    view.setUint8(offset + 5, clampByte((star.bv + 0.4) * 90));
  });

  return bytes;
};

const loadCatalogText = async (path) => {
  if (path) {
    const buffer = await readFile(path);
    return (path.endsWith(".gz") ? gunzipSync(buffer) : buffer).toString("latin1");
  }

  const response = await fetch(SOURCE_URL);

  if (!response.ok) {
    throw new Error(`Download failed: ${response.status} ${response.statusText}`);
  }

  return gunzipSync(Buffer.from(await response.arrayBuffer())).toString("latin1");
};

const stars = parseCatalog(await loadCatalogText(process.argv[2]));
const base64 = Buffer.from(encodeStars(stars)).toString("base64");
const lines = base64.match(/.{1,100}/g).map((chunk) => `  "${chunk}"`);

await writeFile(
  OUTPUT,
  `// Generated by scripts/build-star-catalog.mjs. Do not edit by hand.
// Yale Bright Star Catalogue, 5th Revised Ed. (Hoffleit & Warren 1991), via CDS VizieR V/50.
// ${stars.length} stars, brightest first, 6 bytes each (see the script for the layout).

export const BRIGHT_STAR_COUNT = ${stars.length};

export const BRIGHT_STARS_BASE64 =
${lines.join(" +\n")};
`
);

console.log(`Wrote ${stars.length} stars (${base64.length} base64 chars) to ${OUTPUT}`);
